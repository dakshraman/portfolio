export function detectUserCountry() {
  if (typeof window === 'undefined') return DEFAULT_COUNTRY;

  // 1. Check saved user preference in localStorage
  try {
    const savedCode = localStorage.getItem('user_country_code');
    if (savedCode) {
      const match = ALL_COUNTRIES.find((c) => c.code === savedCode);
      if (match) return match;
    }
  } catch (e) {}

  // 2. Detect from browser timezone
  try {
    const tz = Intl.DateTimeFormat().resolvedOptions().timeZone;
    if (tz) {
      // Direct exact match
      const countryCode = TIMEZONE_TO_COUNTRY[tz];
      if (countryCode) {
        const found = ALL_COUNTRIES.find((c) => c.code === countryCode);
        if (found) return found;
      }
      
      // Continent prefix heuristic
      if (tz.startsWith('America/')) {
        const us = ALL_COUNTRIES.find((c) => c.code === 'US');
        if (us) return us;
      }
      if (tz.startsWith('Europe/')) {
        const gb = ALL_COUNTRIES.find((c) => c.code === 'GB');
        if (gb) return gb;
      }
      if (tz.startsWith('Australia/')) {
        const au = ALL_COUNTRIES.find((c) => c.code === 'AU');
        if (au) return au;
      }
    }
  } catch (e) {}

  // 3. Detect from navigator language
  try {
    const lang = navigator.language || (navigator.languages && navigator.languages[0]);
    if (lang && lang.includes('-')) {
      const countryCode = lang.split('-')[1].toUpperCase();
      const found = ALL_COUNTRIES.find((c) => c.code === countryCode);
      if (found) return found;
    }
  } catch (e) {}

  return DEFAULT_COUNTRY;
}

/**
 * Cleanly format USD values into target country currency with clean rounding
 */
export function formatCurrencyPrice(usdAmount, country) {
  if (!country) return `$${usdAmount.toLocaleString()}`;
  
  const converted = usdAmount * (country.rate || 1.0);
  
  // Intelligent rounding based on currency scale
  let rounded = converted;
  if (country.rate > 1000) {
    // Large currencies like JPY, KRW, IDR, VND -> round to nearest 100 or 1000
    rounded = Math.round(converted / 100) * 100;
  } else if (country.rate > 50) {
    // Currencies like INR, PHP, THB -> round to nearest 10 or 100
    rounded = Math.round(converted / 50) * 50;
  } else if (country.rate > 5) {
    // Currencies like ZAR, BRL, MXN, SEK, NOK -> round to nearest 5
    rounded = Math.round(converted / 5) * 5;
  } else {
    // Currencies like USD, EUR, GBP, CAD, AUD, CHF -> round to nearest 5 or 10
    rounded = Math.round(converted / 5) * 5;
  }

  // Format with localized thousands separator
  const formattedNumber = rounded.toLocaleString();
  
  if (country.symbol === 'AED' || country.symbol === 'SAR' || country.symbol === 'CHF') {
    return `${country.symbol} ${formattedNumber}`;
  }
  
  return `${country.symbol}${formattedNumber}`;
}
